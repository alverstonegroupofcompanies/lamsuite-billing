import type {
  ReportModule,
  ReportQueryParams,
  ReportQueryResult,
  PrintableDocumentData,
} from "../types";
import { exportEngine } from "./ExportEngine";
import { printFormatter } from "./PrintFormatter";
import { companySettingsService } from "../../lib/settings/companySettingsService";

export class ReportRunner {
  /**
   * Execute report query and compute column totals if missing
   */
  async executeReport<TFilter, TRow, TSummary>(
    module: ReportModule<TFilter, TRow, TSummary>,
    params: ReportQueryParams<TFilter>
  ): Promise<ReportQueryResult<TRow, TSummary>> {
    const finalParams: ReportQueryParams<TFilter> = {
      ...params,
      sort: params.sort || module.defaultSort,
    };

    const result = await module.runQuery(finalParams);

    // If summary is not generated by query, compute totals from column totalType definitions
    if (!result.summary && result.rows.length > 0) {
      const computedSummary: Record<string, any> = {};
      for (const col of module.columns) {
        if (col.totalType === "sum") {
          const sum = result.rows.reduce((acc, row) => acc + (Number(col.accessor(row)) || 0), 0);
          computedSummary[col.id] = Math.round(sum * 100) / 100;
        } else if (col.totalType === "count") {
          computedSummary[col.id] = result.rows.length;
        } else if (col.totalType === "avg") {
          const sum = result.rows.reduce((acc, row) => acc + (Number(col.accessor(row)) || 0), 0);
          computedSummary[col.id] = result.rows.length > 0 ? Math.round((sum / result.rows.length) * 100) / 100 : 0;
        }
      }
      result.summary = computedSummary as TSummary;
    }

    return result;
  }

  /**
   * Export report data to CSV
   */
  async exportCsv<TFilter, TRow, TSummary>(
    module: ReportModule<TFilter, TRow, TSummary>,
    rows: TRow[],
    visibleColumnIds?: string[],
    filterLabel?: string
  ): Promise<void> {
    const filename = `${module.id}_${filterLabel || new Date().toISOString().slice(0, 10)}.csv`;
    exportEngine.exportReport(filename, module.columns, rows, visibleColumnIds);
  }

  /**
   * Prepare printable document structure for native printing or preview
   */
  async preparePrintableDocument<TFilter, TRow, TSummary>(
    module: ReportModule<TFilter, TRow, TSummary>,
    result: ReportQueryResult<TRow, TSummary>,
    filters: TFilter,
    visibleColumnIds?: string[]
  ): Promise<PrintableDocumentData> {
    const settings = await companySettingsService.loadSettings();
    const activeCols = visibleColumnIds
      ? module.columns.filter((c) => visibleColumnIds.includes(c.id))
      : module.columns.filter((c) => c.isDefaultVisible);

    const storeDetails = {
      storeName: settings.store_name || "LamStone Pharmacy & Retail",
      address: settings.address || "Main Road, Palakkad, Kerala",
      phone: settings.phone || "9876543210",
      gstin: settings.gstin,
      dlNo: settings.drug_license_numbers?.[0],
    };

    if (module.buildPrintDocument) {
      return module.buildPrintDocument(result, filters, storeDetails);
    }

    // Default document builder
    const headers = activeCols.map((c) => ({
      id: c.id,
      label: c.header,
      align: c.align || "left",
      format: c.format,
      width: c.width,
    }));

    const rows = result.rows.map((row) => {
      const obj: Record<string, any> = {};
      for (const col of activeCols) {
        obj[col.id] = col.accessor(row);
      }
      if ((row as any).items_summary) {
        obj.items_summary = (row as any).items_summary;
      }
      return obj;
    });

    const formatDisplayDate = (d: string): string => {
      if (!d || typeof d !== "string") return String(d || "");
      const match = d.match(/^(\d{4})-(\d{2})-(\d{2})/);
      if (match) return `${match[3]}/${match[2]}/${match[1]}`;
      return d;
    };

    const filterSummary: Array<{ label: string; value: string }> = [];
    if (filters && typeof filters === "object") {
      const filterObj = filters as Record<string, any>;
      const skipKeys = new Set<string>();

      // Gracefully handle date ranges
      if (filterObj.date_range && typeof filterObj.date_range === "object") {
        const dr = filterObj.date_range;
        const start = dr.startDate || dr.start || dr.from;
        const end = dr.endDate || dr.end || dr.to;
        if (start && end) {
          if (start === end) {
            filterSummary.push({ label: "DATE", value: formatDisplayDate(start) });
          } else {
            filterSummary.push({ label: "PERIOD", value: `${formatDisplayDate(start)} to ${formatDisplayDate(end)}` });
          }
        }
        skipKeys.add("date_range");
        skipKeys.add("startDate");
        skipKeys.add("endDate");
        skipKeys.add("start_date");
        skipKeys.add("end_date");
      } else if (filterObj.startDate && filterObj.endDate) {
        const start = String(filterObj.startDate);
        const end = String(filterObj.endDate);
        if (start === end) {
          filterSummary.push({ label: "DATE", value: formatDisplayDate(start) });
        } else {
          filterSummary.push({ label: "PERIOD", value: `${formatDisplayDate(start)} to ${formatDisplayDate(end)}` });
        }
        skipKeys.add("startDate");
        skipKeys.add("endDate");
        skipKeys.add("start_date");
        skipKeys.add("end_date");
      }

      for (const [k, v] of Object.entries(filterObj)) {
        if (skipKeys.has(k)) continue;
        if (v === undefined || v === null || v === "" || v === "all") continue;

        let formattedVal = "";
        if (typeof v === "object") {
          if (Array.isArray(v)) {
            formattedVal = v.join(", ");
          } else {
            formattedVal = (v as any).label || (v as any).name || (v as any).title || "";
          }
        } else if (typeof v === "string" && /^\d{4}-\d{2}-\d{2}/.test(v)) {
          formattedVal = formatDisplayDate(v);
        } else {
          formattedVal = String(v);
        }

        if (formattedVal && formattedVal !== "[object Object]") {
          filterSummary.push({ label: k.replace(/_/g, " ").toUpperCase(), value: formattedVal });
        }
      }
    }

    const totalsObj: Record<string, any> = {};
    if (result.summary && typeof result.summary === "object") {
      for (const col of activeCols) {
        if ((result.summary as any)[col.id] !== undefined) {
          totalsObj[col.id] = (result.summary as any)[col.id];
        }
      }
    }

    return {
      title: module.title,
      subtitle: module.description,
      storeDetails,
      filterSummary,
      generatedAt: new Date().toLocaleString("en-IN"),
      headers,
      rows,
      totals: Object.keys(totalsObj).length > 0 ? totalsObj : undefined,
    };
  }
}

export const reportRunner = new ReportRunner();
